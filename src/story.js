// Концовка зависит от того, скольких героинь отряд пощадил (из всех шести).
export function endingFor(spared) {
  if (spared >= 5) {
    return [
      { who: 'narrator', text: 'Великая Рыба вернулась в Мурград, а вместе с ней — шумная компания воительниц.' },
      { who: 'narrator', text: 'По вечерам Сакура учит котиков фехтованию, Юки делает мороженое, а Императрица гладит каждого, кто подойдёт.' },
    ];
  }
  if (spared >= 2) {
    return [
      { who: 'narrator', text: 'Рыба вернулась домой, и миски снова полны.' },
      { who: 'narrator', text: 'Иногда в деревню заглядывают старые знакомые — поиграть и поесть рыбки.' },
    ];
  }
  return [
    { who: 'narrator', text: 'Рыба вернулась, но в Мурграде стало как-то тихо.' },
    { who: 'narrator', text: 'Может, в следующий раз стоит быть добрее?' },
  ];
}

