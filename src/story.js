// Номер главы (0..5), если этот этап — финальная битва главы; иначе -1. После 60-го этапа главы идут по кругу.
export function chapterForStage(stage) {
  if (stage % 10 !== 0) return -1;
  return (stage / 10 - 1) % CHAPTERS.length;
}

export const heroineForStage = (stage) => {
  const ch = chapterForStage(stage);
  return ch >= 0 ? HEROINES[ch] : null;
};
