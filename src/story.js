export function endingKind(spared) {
  return spared >= 5 ? 'good' : spared >= 2 ? 'mid' : 'bad';
}

export const endingId = (book, kind) => `b${book + 1}-${kind}`;

export function endingFor(book, spared) {
  return ENDINGS[book][endingKind(spared)];
}

